import os
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_pdf_report(summary_data, df_predictions, file_path):
    """
    Generates a professional PDF Churn Prediction Report using ReportLab.

    Parameters:
    - summary_data: dict containing keys like 'total_customers', 'churn_count', 'churn_rate', 'avg_confidence'
    - df_predictions: DataFrame of predictions (must contain customer ID, churn probability, churn prediction, etc.)
    - file_path: output path for the PDF
    """
    os.makedirs(os.path.dirname(file_path), exist_ok=True)

    # Create Document
    doc = SimpleDocTemplate(
        file_path,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()

    # Custom Styles
    primary_color = colors.HexColor("#1e1b4b")  # Deep Navy/Indigo
    secondary_color = colors.HexColor("#4f46e5")  # Purple
    light_bg = colors.HexColor("#f8fafc")  # Off-white
    text_color = colors.HexColor("#1e293b")  # Charcoal
    accent_red = colors.HexColor("#ef4444")  # Red
    accent_green = colors.HexColor("#22c55e")  # Green

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=24,
        textColor=colors.white,
        spaceAfter=12,
        alignment=0  # Left
    )

    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        textColor=colors.HexColor("#cbd5e1"),
        spaceAfter=6
    )

    h2_style = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=16,
        textColor=primary_color,
        spaceBefore=15,
        spaceAfter=10,
        borderColor=secondary_color,
        borderWidth=1,
        borderPadding=4
    )

    body_style = ParagraphStyle(
        'BodyText',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        textColor=text_color,
        leading=14,
        spaceAfter=8
    )

    bullet_style = ParagraphStyle(
        'BulletText',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        textColor=text_color,
        leading=14,
        leftIndent=15,
        spaceAfter=6
    )

    bold_body_style = ParagraphStyle(
        'BoldBodyText',
        parent=body_style,
        fontName='Helvetica-Bold'
    )

    story = []

    # 1. Header Banner Table
    header_data = [
        [
            Paragraph("Customer Churn Prediction Report", title_style),
            Paragraph("<b>System Output</b><br/>Date: 2026-07-22<br/>Classification: Confidential", ParagraphStyle('HRight', parent=subtitle_style, alignment=2))
        ],
        [
            Paragraph("Executive analytics dashboard and machine learning prediction insights.", subtitle_style),
            ""
        ]
    ]

    header_table = Table(header_data, colWidths=[380, 160])
    header_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), primary_color),
        ('PADDING', (0,0), (-1,-1), 16),
        ('SPAN', (0,1), (1,1)),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
    ]))

    story.append(header_table)
    story.append(Spacer(1, 15))

    # 2. Executive Summary / KPI Cards
    story.append(Paragraph("Executive Summary", h2_style))
    story.append(Paragraph(
        "This report provides a customer risk analysis generated by the machine learning churn prediction engine. "
        "The model analyzes customer tenure, monthly charges, contract types, and service subscriptions "
        "to evaluate individual churn probabilities and categorize accounts by risk level.", body_style
    ))
    story.append(Spacer(1, 8))

    # KPI Grid (Table)
    total_cust = summary_data.get('total_customers', 0)
    churn_cnt = summary_data.get('churn_count', 0)
    churn_rt = summary_data.get('churn_rate', 0.0)
    avg_conf = summary_data.get('avg_confidence', 0.0)

    kpi_data = [
        [
            Paragraph(f"<font size=10 color='#64748b'>TOTAL CUSTOMERS</font><br/><br/><font size=20><b>{total_cust}</b></font>", body_style),
            Paragraph(f"<font size=10 color='#64748b'>PREDICTED CHURN</font><br/><br/><font size=20 color='#ef4444'><b>{churn_cnt}</b></font>", body_style)
        ],
        [
            Paragraph(f"<font size=10 color='#64748b'>CHURN RATE</font><br/><br/><font size=20 color='#ef4444'><b>{churn_rt:.1f}%</b></font>", body_style),
            Paragraph(f"<font size=10 color='#64748b'>AVG CONFIDENCE</font><br/><br/><font size=20 color='#3b82f6'><b>{avg_conf:.1f}%</b></font>", body_style)
        ]
    ]

    kpi_table = Table(kpi_data, colWidths=[270, 270])
    kpi_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), light_bg),
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('PADDING', (0,0), (-1,-1), 15),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#e2e8f0")),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor("#e2e8f0")),
    ]))
    story.append(kpi_table)
    story.append(Spacer(1, 15))

    # 3. High-Risk Customer List
    story.append(Paragraph("Top High-Risk Customers (Sorted by Risk Probability)", h2_style))

    # Prepare Table Data
    table_content = [[
        Paragraph("<b>Customer ID</b>", bold_body_style),
        Paragraph("<b>Prediction</b>", bold_body_style),
        Paragraph("<b>Probability</b>", bold_body_style),
        Paragraph("<b>Risk Category</b>", bold_body_style)
    ]]

    # Sort prediction df to get top risk customers
    df_sorted = df_predictions.sort_values(by="probability", ascending=False).head(10)

    for idx, row in df_sorted.iterrows():
        cust_id = row.get("customerID", "Unknown")
        pred = row.get("prediction", "Stay")
        prob = row.get("probability", 0.0)

        # Determine risk level
        if prob >= 0.8:
            risk_label = "<font color='#ef4444'><b>High Risk</b></font>"
        elif prob >= 0.5:
            risk_label = "<font color='#f59e0b'><b>Medium Risk</b></font>"
        else:
            risk_label = "<font color='#22c55e'><b>Low Risk</b></font>"

        pred_label = f"<font color='#ef4444'><b>{pred}</b></font>" if pred == "Churn" else f"<font color='#22c55e'><b>{pred}</b></font>"

        table_content.append([
            Paragraph(cust_id, body_style),
            Paragraph(pred_label, body_style),
            Paragraph(f"{prob * 100:.1f}%", body_style),
            Paragraph(risk_label, body_style)
        ])

    risk_table = Table(table_content, colWidths=[150, 120, 120, 150])

    # Table Styling
    t_style = [
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")),
        ('PADDING', (0,0), (-1,-1), 8),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#cbd5e1")),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
    ]
    # Add alternating row colors
    for i in range(1, len(table_content)):
        if i % 2 == 0:
            t_style.append(('BACKGROUND', (0, i), (-1, i), colors.HexColor("#f1f5f9")))

    risk_table.setStyle(TableStyle(t_style))
    story.append(risk_table)
    story.append(Spacer(1, 15))

    # 4. AI Insights & Strategic Recommendations
    story.append(Paragraph("AI-Generated Insights & Churn Reduction Strategies", h2_style))

    insights = summary_data.get('insights', [])
    recommendations = summary_data.get('recommendations', [])

    story.append(Paragraph("<b>Key Risk Drivers Detected:</b>", bold_body_style))
    if insights:
        for ins in insights:
            story.append(Paragraph(f"• {ins}", bullet_style))
    else:
        story.append(Paragraph("• Customers on short tenure with Month-to-Month contracts have the highest risk of churn.", bullet_style))
        story.append(Paragraph("• Higher monthly charges combined with Fiber Optic service correlated with increased churn rate.", bullet_style))
        story.append(Paragraph("• Lack of premium add-ons (like Online Security or Tech Support) increases customer churn likelihood.", bullet_style))

    story.append(Spacer(1, 6))
    story.append(Paragraph("<b>Recommended Retention Tactics:</b>", bold_body_style))
    if recommendations:
        for rec in recommendations:
            story.append(Paragraph(f"• <b>{rec.split(':')[0]}:</b>{rec.split(':')[1] if ':' in rec else ''}", bullet_style))
    else:
        story.append(Paragraph("• <b>Contract Upgrades:</b> Incentivize Month-to-Month customers with high churn risk to switch to 1-Year or 2-Year contracts by offering a 10-15% discount.", bullet_style))
        story.append(Paragraph("• <b>Promotional Bundling:</b> Target high-paying Fiber Optic customers with loyalty discounts or value-added services like free Tech Support or Online Security trials.", bullet_style))
        story.append(Paragraph("• <b>Customer Service Outreach:</b> Initiate proactive check-ins for customers in their first 6 months of tenure to address early onboarding friction.", bullet_style))
        story.append(Paragraph("• <b>Billing Options:</b> Encourage customers using paper checks to migrate to Credit Card or Bank Transfer Auto-pay to reduce payment-related friction.", bullet_style))

    story.append(Spacer(1, 20))

    # Footer Notice
    story.append(Paragraph("<font size=8 color='#94a3b8'>Report generated automatically by the Customer Churn Prediction System. Model predictions are probabilistic and should be used to support strategic retention outreach.</font>", ParagraphStyle('FNotice', parent=body_style, alignment=1)))

    # Build PDF
    doc.build(story)
    print(f"PDF Report generated at: {file_path}")
